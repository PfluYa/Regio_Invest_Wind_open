%% FIGURE 3: INSTALLED CAPACITY BY TURBINE TYPE IN 2040

scriptPath = mfilename('fullpath');
scriptFolder = fileparts(scriptPath);
repoFolder = fileparts(scriptFolder);
resultsFolder = fullfile(repoFolder, 'Results Paper');

inputFile = fullfile( ...
    resultsFolder, ...
    'results_nuts3_base2024_target2040_expCase1_capacity.mat');

outputFile = fullfile( ...
    resultsFolder, ...
    'Figure_3_turbine_types.pdf');

if ~isfile(inputFile)
    error('2040 baseline result file not found: %s', inputFile);
end

S = load( ...
    inputFile, ...
    'resultsWindOnshoreTurbinesUnstack');

if ~isfield(S, 'resultsWindOnshoreTurbinesUnstack')
    error([ ...
        'The 2040 result file does not contain ', ...
        'resultsWindOnshoreTurbinesUnstack. Re-run the scenario first.']);
end

plot_results( ...
    S.resultsWindOnshoreTurbinesUnstack, ...
    [], ...
    outputFile);

fprintf('Figure 3 saved to:\n%s\n', outputFile);
