%% FIGURE 6: CAPACITY DIFFERENCE WITH VS. WITHOUT REFERENCE-YIELD MODEL
% Positive values indicate higher projected capacity without the
% reference-yield mechanism. Negative values indicate lower projected
% capacity without the reference-yield mechanism.
%
% Relative differences are clipped at +/- 50 percent for readability.
%
% Grey regions indicate either:
%   (i) negligible installed capacity in both scenarios, defined here as
%       less than 5 MW in both cases; or
%   (ii) an undefined relative difference (e.g. 0/0).
%
% Note:
% capacityTotal is measured in kW, hence 5 MW = 5e3 kW.

scriptPath = ...
    mfilename('fullpath');

scriptFolder = ...
    fileparts(scriptPath);

repoFolder = ...
    fileparts(scriptFolder);

resultsFolder = ...
    fullfile(repoFolder, 'Results Paper');


%% ------------------------------------------------------------------------
% 1. LOAD RESULTS
% -------------------------------------------------------------------------

fileWithRYM = ...
    fullfile( ...
        resultsFolder, ...
        'results_nuts3_base2024_target2040_expCase1_capacity.mat');

fileWithoutRYM = ...
    fullfile( ...
        resultsFolder, ...
        'results_nuts3_base2024_target2040_expCase1_capacity_no_reference_yield.mat');

if ~isfile(fileWithRYM)

    error( ...
        'Result with reference-yield mechanism not found: %s', ...
        fileWithRYM);
end

if ~isfile(fileWithoutRYM)

    error( ...
        'Result without reference-yield mechanism not found: %s', ...
        fileWithoutRYM);
end

S_with = ...
    load( ...
        fileWithRYM, ...
        'selected_data');

S_without = ...
    load( ...
        fileWithoutRYM, ...
        'selected_data');

withRYM = ...
    S_with.selected_data;

withoutRYM = ...
    S_without.selected_data;


%% ------------------------------------------------------------------------
% 2. ALIGN DATA BY NUTS3 ID
% -------------------------------------------------------------------------

[isMatched, idxWith] = ...
    ismember( ...
        withoutRYM.nutsID, ...
        withRYM.nutsID);

if any(~isMatched)

    error( ...
        'Mismatch in NUTS3 IDs between the two result files.');
end

capacityWithRYM = ...
    withRYM.capacityTotal(idxWith);

capacityWithoutRYM = ...
    withoutRYM.capacityTotal;


%% ------------------------------------------------------------------------
% 3. CALCULATE RELATIVE DIFFERENCE
% -------------------------------------------------------------------------

relativeDifference = ...
    (capacityWithoutRYM - capacityWithRYM) ./ ...
    capacityWithRYM;

% Regions with negligible capacity in both scenarios are not assigned a
% percentage change because the relative difference is economically
% uninformative for such small absolute quantities.
lowCapacityThreshold = ...
    5e3;  % 5 MW, because capacityTotal is measured in kW

lowCapacityMask = ...
    (capacityWithRYM < lowCapacityThreshold) & ...
    (capacityWithoutRYM < lowCapacityThreshold);

relativeDifference(lowCapacityMask) = ...
    NaN;

% Preserve the behavior of the original plotting script:
% 0/0 remains NaN and is shown in grey.
% A positive value divided by zero yields +Inf and is subsequently clipped
% to +50 percent rather than treated as missing.


%% ------------------------------------------------------------------------
% 4. PREPARE VISUALIZATION
% -------------------------------------------------------------------------

clipLimit = ...
    0.5;

valuesClipped = ...
    min( ...
        max( ...
            relativeDifference, ...
            -clipLimit), ...
        clipLimit);

% Diverging magenta-white-cyan palette:
%   negative -> magenta
%   zero     -> white
%   positive -> cyan
nHalf = ...
    128;

negativeColors = [ ...
    ones(nHalf, 1), ...
    linspace(0, 1, nHalf)', ...
    ones(nHalf, 1)];

positiveColors = [ ...
    linspace(1, 0, nHalf)', ...
    ones(nHalf, 1), ...
    ones(nHalf, 1)];

colorMap = ...
    [ ...
        negativeColors; ...
        positiveColors(2:end, :) ...
    ];


%% ------------------------------------------------------------------------
% 5. PLOT MAP
% -------------------------------------------------------------------------

fig = ...
    figure( ...
        'Position', ...
        [180 100 720 850], ...
        'Color', ...
        'w');

ax = ...
    axes(fig);

hold(ax, 'on');

for iRegion = 1:height(withoutRYM)

    regionShape = ...
        polyshape( ...
            withoutRYM.lonPoly{iRegion}, ...
            withoutRYM.latPoly{iRegion});

    value = ...
        valuesClipped(iRegion);

    if isnan(relativeDifference(iRegion))

        % Negligible capacity in both scenarios or undefined relative
        % difference.
        faceColor = ...
            [0.55 0.55 0.55];

    elseif value <= 0

        weight = ...
            (value + clipLimit) ./ ...
            clipLimit;

        faceColor = ...
            [1, weight, 1];

    else

        weight = ...
            value ./ ...
            clipLimit;

        faceColor = ...
            [1 - weight, 1, 1];
    end

    plot( ...
        ax, ...
        regionShape, ...
        'FaceColor', ...
        faceColor, ...
        'FaceAlpha', ...
        0.90, ...
        'EdgeColor', ...
        [0.70 0.70 0.70], ...
        'LineWidth', ...
        0.25);
end


%% ------------------------------------------------------------------------
% 6. COLORBAR
% -------------------------------------------------------------------------

colormap( ...
    ax, ...
    colorMap);

clim( ...
    ax, ...
    [-clipLimit, clipLimit]);

cb = ...
    colorbar(ax);

cb.Ticks = ...
    [-0.5, 0, 0.5];

cb.TickLabels = ...
    {'-50%', '0%', '+50%'};

cb.Label.String = ...
    '';


%% ------------------------------------------------------------------------
% 7. AXIS SETTINGS
% -------------------------------------------------------------------------

axis(ax, 'equal');
axis(ax, 'off');

xlim( ...
    ax, ...
    [ ...
        min(withoutRYM.lonPoint) - 0.3, ...
        max(withoutRYM.lonPoint) + 0.3 ...
    ]);

ylim( ...
    ax, ...
    [ ...
        min(withoutRYM.latPoint) - 0.3, ...
        max(withoutRYM.latPoint) + 0.3 ...
    ]);

hold(ax, 'off');


%% ------------------------------------------------------------------------
% 8. DIAGNOSTIC OUTPUT
% -------------------------------------------------------------------------

fprintf('\n');
fprintf('============================================================\n');
fprintf('FIGURE 6: REFERENCE-YIELD DIFFERENCE MAP\n');
fprintf('============================================================\n\n');

fprintf( ...
    'Grey-region threshold: %.1f MW in both scenarios\n', ...
    lowCapacityThreshold ./ 1e3);

fprintf( ...
    'Number of grey regions: %d of %d\n', ...
    sum(isnan(relativeDifference)), ...
    height(withoutRYM));

fprintf( ...
    'Regions below the capacity threshold in both scenarios: %d\n', ...
    sum(lowCapacityMask));


%% ------------------------------------------------------------------------
% 9. EXPORT
% -------------------------------------------------------------------------

outputFile = ...
    fullfile( ...
        resultsFolder, ...
        'Figure_6_reference_yield_difference.pdf');

exportgraphics( ...
    fig, ...
    outputFile, ...
    'ContentType', ...
    'vector');

fprintf( ...
    'Figure 6 saved to:\n%s\n', ...
    outputFile);