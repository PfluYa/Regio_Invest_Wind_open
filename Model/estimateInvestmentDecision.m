function [marketData, newInvestments, regionalCapacities, resultsScaling] = ...
    estimateInvestmentDecision( ...
        inpDiscreteChoiceModel, ...
        inpMarket, ...
        inpTargetInvestments, ...
        inpParaTech, ...
        optsScaleAreaInvest, ...
        optsNpvAdjust, ...
        optsRefYieldInInvestment, ...
        paraOPEXfix, ...
        paraOPEXperkWhvar, ...
        paraRegioInvest, ...
        optsRegioInvest)
% ESTIMATEINVESTMENTDECISION
%
% Estimates regional wind-power investment using the estimated nested-logit
% model. The function supports capacity-based and energy-based target
% calibration and computes:
%
%   - installed capacity and annual electricity generation,
%   - required and production-weighted remuneration,
%   - annualized NPV-based producer surplus,
%   - synthetic probability-based producer surplus,
%   - subsidy expenditure,
%   - resource-cost-based welfare,
%   - probability-based synthetic net benefits,
%   - avoided variable gas and CO2 costs,
%   - regional capacity aggregates,
%   - diagnostics for scaleRefYield = 1,
%   - a formatted summary table for selected scaling scenarios.
%
% INTERPRETATION
%
% The probability-based producer-surplus measure is derived from the
% remuneration response implied by the estimated nested-logit model and is
% the main behaviorally based evaluation measure used in the paper.
%
% NPV-based producer surplus and the resource-cost-based welfare measure are
% retained as complementary benchmarks based on explicit remuneration,
% investment, and operating-cost flows.


%% ========================================================================
% 0. GLOBAL PARAMETERS USED BY NESTED LOGIT
% ========================================================================

global beta alpha gamma lambda nrAlt nrDecisionMaker


%% ========================================================================
% 1. LOAD AND PREPARE INPUT DATA
% ========================================================================

discreteChoiceModel  = inpDiscreteChoiceModel;
dcmParam             = discreteChoiceModel.discreteChoiceParam;
nrAlt                = discreteChoiceModel.nrAlternatives;
explanatoryVariables = discreteChoiceModel.explanatoryVariables;

marketData      = inpMarket;
nrDecisionMaker = numel(unique(marketData.nutsID));


%% ========================================================================
% 2. EXTRACT TECHNICAL PARAMETERS
% ========================================================================

compensation         = inpParaTech.paraCompensation;
interestRate         = inpParaTech.paraInterestRate;
powerPotential       = inpParaTech.paraPowerPotential;
powerPotentialInvest = inpParaTech.paraPowerPotentialInvest;
turbineLifetime      = inpParaTech.paraTurbineLifetime;
investFactor         = inpParaTech.paraInvestFactor;

production   = marketData.production;
powerTurbine = marketData.powerTurbine;

origCompensation = compensation;


%% ========================================================================
% 3. CHECK AND ADAPT AREA CONSTRAINTS
% ========================================================================

[groups, nutsID] = findgroups(marketData.nutsID);

summedCapacitiesBaseYear = ...
    splitapply(@sum, marketData.capacitiesBaseYear, groups);

summedCapacitiesDiscreteChoice = ...
    splitapply(@sum, marketData.capacitiesDiscreteChoice, groups);

summedCapacitiesInSimYear = ...
    splitapply(@sum, marketData.capacitiesInSimYear, groups);

totalArea = ...
    splitapply(@(x) x(1), marketData.totalArea, groups);

relativeAvailableWindSpace = ...
    splitapply( ...
        @(x) x(1), ...
        marketData.relativeAvailableWindSpace, ...
        groups);

relativeAvailableWindSpaceWindBG = ...
    splitapply( ...
        @(x) x(1), ...
        marketData.relativeAvailableWindSpace_WindBG, ...
        groups);

relativeAvailableWindSpaceBWE = ...
    splitapply( ...
        @(x) x(1), ...
        marketData.relativeAvailableWindSpace_BWE, ...
        groups);

relativeAvailableWindSpaceUB21 = ...
    splitapply( ...
        @(x) x(1), ...
        marketData.relativeAvailableWindSpace_UB21, ...
        groups);

tableAdaptWindBG = table( ...
    nutsID, ...
    totalArea, ...
    relativeAvailableWindSpace, ...
    relativeAvailableWindSpaceWindBG, ...
    relativeAvailableWindSpaceBWE, ...
    relativeAvailableWindSpaceUB21, ...
    summedCapacitiesBaseYear, ...
    summedCapacitiesDiscreteChoice, ...
    summedCapacitiesInSimYear);

tableAdaptWindBG.usedAreaBase = ...
    splitapply( ...
        @sum, ...
        marketData.capacitiesBaseYear ./ powerPotential, ...
        groups);

tableAdaptWindBG.usedAreaBaseRelative = ...
    tableAdaptWindBG.usedAreaBase ./ ...
    tableAdaptWindBG.totalArea;

tableAdaptWindBG.index = ...
    tableAdaptWindBG.usedAreaBaseRelative > ...
    0.9 .* tableAdaptWindBG.relativeAvailableWindSpaceWindBG;

tableAdaptWindBG.relativeAvailableWindSpaceWindBG( ...
    tableAdaptWindBG.index) = ...
    1.1 .* max( ...
        tableAdaptWindBG.relativeAvailableWindSpaceWindBG( ...
            tableAdaptWindBG.index), ...
        tableAdaptWindBG.usedAreaBaseRelative( ...
            tableAdaptWindBG.index));

expandedWindBG = ...
    repelem( ...
        tableAdaptWindBG.relativeAvailableWindSpaceWindBG, ...
        nrAlt);

marketData.relativeAvailableWindSpace_WindBG = ...
    expandedWindBG;


%% ========================================================================
% 4. AVAILABLE LAND UNDER CHOSEN AREA SCENARIO
% ========================================================================

switch optsScaleAreaInvest

    case 'none'

        marketData.availableWindSpaceSim = ...
            marketData.relativeAvailableWindSpace .* ...
            marketData.totalArea;

    case 'BWE'

        marketData.availableWindSpaceSim = ...
            marketData.relativeAvailableWindSpace_BWE .* ...
            marketData.totalArea;

    case 'WindBG'

        marketData.availableWindSpaceSim = ...
            marketData.relativeAvailableWindSpace_WindBG .* ...
            marketData.totalArea;

    case 'UB21'

        marketData.availableWindSpaceSim = ...
            marketData.relativeAvailableWindSpace_UB21 .* ...
            marketData.totalArea;

    otherwise

        error('Invalid entry for optsScaleAreaInvest.');
end

availableSpace = ...
    max(marketData.availableWindSpaceSim, 0);

compensationFactor = ...
    marketData.compensationFactor;


%% ========================================================================
% 5. REGIONAL CLUSTERS: NORTH / SOUTH / NEUTRAL
% ========================================================================

nuts3 = string(marketData.nutsID);

southList = [ ...
"DE145","DE121","DE146","DE112","DE147","DE132","DE12A","DE133","DE12B","DE113", ...
"DE131","DE12C","DE114","DE125","DE11C","DE117","DE118","DE119","DE122","DE123", ...
"DE138","DE139","DE115","DE11B","DE126","DE127","DE11D","DE129","DE124","DE148", ...
"DE116","DE141","DE128","DE135","DE11A","DE136","DE149","DE111","DE142","DE137", ...
"DE144","DE13A","DE143","DE275","DE214","DE231","DE234","DE251","DE256","DE261", ...
"DE264","DE271","DE276","DE216","DE241","DE245","DE242","DE246","DE215","DE235", ...
"DE217","DE224","DE277","DE22C","DE27D","DE218","DE219","DE21A","DE252","DE257", ...
"DE248","DE21B","DE225","DE21C","DE253","DE258","DE21D","DE278","DE267","DE211", ...
"DE272","DE226","DE273","DE268","DE21E","DE221","DE227","DE27A","DE26A","DE274", ...
"DE21F","DE269","DE21G","DE212","DE21H","DE21I","DE236","DE25A","DE237","DE279", ...
"DE254","DE259","DE27E","DE27B","DE222","DE228","DE21J","DE229","DE232","DE238", ...
"DE213","DE21K","DE25B","DE22A","DE255","DE239","DE262","DE26B","DE21L","DE223", ...
"DE22B","DE23A","DE21M","DE27C","DE233","DE21N","DE25C","DE263","DE26C","DE715", ...
"DE711","DE716","DE717","DE71B","DE71C","DEB3B","DEB3C","DEB14","DEB22","DEB15", ...
"DEB3D","DEB23","DEB31","DEB3E","DEB32","DEB3F","DEB3G","DEB33","DEB34","DEB35", ...
"DEB3J","DEB36","DEB37","DEB1D","DEB3I","DEB38","DEB3H","DEB3K","DEB21","DEB25", ...
"DEB39","DEB3A","DEC02","DEC03","DEC01","DEC04","DEC05","DEC06" ];

northList = [ ...
"DE80M","DE804","DE80K","DE803","DE80L","DE80N", ...
"DE942","DE94C","DE94H","DE945","DE94A","DE946","DE94G","DE943","DE94D","DE941", ...
"DE501","DE936","DE502","DE932","DE939","DE600", ...
"DEF09","DEF0D","DEF03","DEF08","DEF0E","DEF05","DEF07","DEF0C", ...
"DEF01","DEF0B","DEF02","DEF0A","DEF04" ];

cluster = ...
    repmat("Neutral", height(marketData), 1);

cluster(ismember(nuts3, southList)) = ...
    "South";

cluster(ismember(nuts3, northList)) = ...
    "North";

overlap = ...
    ismember(nuts3, southList) & ...
    ismember(nuts3, northList);

if any(overlap)

    warning([ ...
        'Some NUTS3 regions appear in both the North and South lists. ', ...
        'They are assigned to South.']);

    cluster(overlap) = ...
        "South";
end

marketData.Cluster = ...
    categorical(cluster);

origMarketData = ...
    marketData;

origCompensationFactor = ...
    compensationFactor;


%% ========================================================================
% 6. TARGETS
% ========================================================================

targetCapacityWind = ...
    inpTargetInvestments .* 1000;

% The energy-based target is derived below from the current-policy
% (s = 1) capacity-target equilibrium rather than being hard-coded.
targetEnergyProduction = ...
    NaN;

tolEnergy = ...
    0.002;


%% ========================================================================
% 7. SET NESTED-LOGIT PARAMETERS
% ========================================================================

alpha = dcmParam{:, ...
    startsWith( ...
        dcmParam.Properties.VariableNames, ...
        'alpha')};

beta = dcmParam{:, ...
    startsWith( ...
        dcmParam.Properties.VariableNames, ...
        'beta')};

gamma = dcmParam{:, ...
    startsWith( ...
        dcmParam.Properties.VariableNames, ...
        'gamma')};

lambda = dcmParam{:, ...
    startsWith( ...
        dcmParam.Properties.VariableNames, ...
        'lambda')};

% Turbine type 4 is the reference category.
alpha = ...
    [alpha(1:3), 0, alpha(4:end)];

alpha = ...
    repmat(alpha', [nrDecisionMaker, 1]);

beta = ...
    repmat(beta, [nrDecisionMaker .* nrAlt, 1]);

gamma = ...
    repmat(gamma, [nrDecisionMaker .* nrAlt, 1]);

lambda = ...
    repmat(lambda, [nrDecisionMaker .* nrAlt, 1]);


%% ========================================================================
% 7B. DERIVE ENERGY TARGET FROM CURRENT-POLICY EQUILIBRIUM
% ========================================================================

if strcmp(optsRegioInvest.iterationLogicInvestment, 'energy')

    targetMarketData = ...
        origMarketData;

    targetCompensationFactor = ...
        origCompensationFactor;

    if ~optsRefYieldInInvestment

        targetCompensationFactor = ...
            ones(size(targetCompensationFactor));
    end

    targetMarketData.investCost = ...
        applyCostReduction( ...
            targetMarketData.investCost, ...
            paraRegioInvest.costReductionRate, ...
            paraRegioInvest.baseYear, ...
            paraRegioInvest.simYear);

    [~, ...
     ~, ...
     ~, ...
     targetEnergyProduction, ...
     ~, ...
     ~, ...
     ~, ...
     ~] = ...
        runInvestmentLoop( ...
            targetMarketData, ...
            production, ...
            turbineLifetime, ...
            interestRate, ...
            origCompensation, ...
            targetCompensationFactor, ...
            paraOPEXfix, ...
            paraOPEXperkWhvar, ...
            optsNpvAdjust, ...
            explanatoryVariables, ...
            powerPotential, ...
            powerPotentialInvest, ...
            powerTurbine, ...
            investFactor, ...
            availableSpace, ...
            'capacity', ...
            targetCapacityWind, ...
            NaN, ...
            tolEnergy);

    fprintf( ...
        'Energy target from the s = 1 capacity equilibrium: %.3f TWh/year\n', ...
        targetEnergyProduction ./ 1e9);
end


%% ========================================================================
% 8. REFERENCE-YIELD SENSITIVITY ANALYSIS
% ========================================================================

refValue = ...
    1.00;

if isfield(optsRegioInvest, 'runReferenceYieldSensitivity')

    runReferenceYieldSensitivity = ...
        optsRegioInvest.runReferenceYieldSensitivity;

else

    runReferenceYieldSensitivity = ...
        false;
end

if runReferenceYieldSensitivity

    scaleVec = ...
        0:0.005:1.7;

else

    % Ordinary regional simulations only require the current-policy
    % equilibrium at s = 1.
    scaleVec = ...
        1.0;
end

nScale = ...
    numel(scaleVec);

% Store only outputs used in the paper and the associated benchmarks.
resultsScaling = table( ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    zeros(nScale,1), ...
    'VariableNames', { ...
        'scaleRefYield', ...
        'installedCapacity_GW', ...
        'annualGeneration_TWh', ...
        'requiredRemuneration_ctperkWh', ...
        'productionWeightedRemuneration_ctperkWh', ...
        'subsidyExpenditure_bnEUR', ...
        'avoidedGasAndCO2Costs_bnEUR', ...
        'producerSurplusProbabilityBased_bnEUR', ...
        'probabilityBasedSyntheticNetBenefit_bnEUR', ...
        'producerSurplusNpvBased_bnEUR', ...
        'resourceCostBasedNetWelfare_bnEUR', ...
        'capacityNorth_GW', ...
        'capacityNeutral_GW', ...
        'capacitySouth_GW'});

baselineDiagnostics = ...
    struct();

baselineState = ...
    struct();


for iScale = 1:nScale

    %% Reset scenario state

    marketData = ...
        origMarketData;

    compensationFactor = ...
        origCompensationFactor;

    compensation = ...
        origCompensation;

    scaleRefYield = ...
        scaleVec(iScale);

    %% Scale correction factors around one

    compensationFactor = ...
        refValue + ...
        scaleRefYield .* ...
        (compensationFactor - refValue);

    if ~optsRefYieldInInvestment

        compensationFactor = ...
            ones(size(compensationFactor));
    end

    %% Apply CAPEX cost reduction

    marketData.investCost = ...
        applyCostReduction( ...
            marketData.investCost, ...
            paraRegioInvest.costReductionRate, ...
            paraRegioInvest.baseYear, ...
            paraRegioInvest.simYear);

    %% Determine remuneration and investment

    [estimatedNewCap, ...
     compensation, ...
     installedCapacity, ...
     totalGenerationAnnual, ...
     countInvestmentIterations, ...
     npv, ...
     npvCostsTotalLifetime, ...
     npvRevenuesTotalLifetime] = ...
        runInvestmentLoop( ...
            marketData, ...
            production, ...
            turbineLifetime, ...
            interestRate, ...
            compensation, ...
            compensationFactor, ...
            paraOPEXfix, ...
            paraOPEXperkWhvar, ...
            optsNpvAdjust, ...
            explanatoryVariables, ...
            powerPotential, ...
            powerPotentialInvest, ...
            powerTurbine, ...
            investFactor, ...
            availableSpace, ...
            optsRegioInvest.iterationLogicInvestment, ...
            targetCapacityWind, ...
            targetEnergyProduction, ...
            tolEnergy);

    %% Store capacities

    marketData.estimatedNewCapacity = ...
        estimatedNewCap;

    marketData.estimatedTotalCapacity = ...
        estimatedNewCap + ...
        marketData.capacitiesInSimYear;

    %% Probability-based producer surplus

    runBaselineDiagnostics = ...
        runReferenceYieldSensitivity && ...
        abs(scaleRefYield - 1.0) < 1e-12;

    if runReferenceYieldSensitivity

        [producerSurplusProbabilityBasedOneYear, ...
         integrationDiagnostics] = ...
            calcIntegratedProducerSurplusFleet( ...
                marketData, ...
                marketData.estimatedTotalCapacity, ...
                compensation, ...
                compensationFactor, ...
                production, ...
                turbineLifetime, ...
                interestRate, ...
                paraOPEXfix, ...
                paraOPEXperkWhvar, ...
                optsNpvAdjust, ...
                explanatoryVariables, ...
                powerPotential, ...
                powerTurbine, ...
                runBaselineDiagnostics);

    else

        % Probability-based policy-evaluation measures are only required
        % for the reference-yield sensitivity analysis used in Table 3
        % and Figures 7 and 9.
        producerSurplusProbabilityBasedOneYear = ...
            NaN;

        integrationDiagnostics = ...
            struct();
    end

    %% Production-weighted effective remuneration

    totalGenerationByAlternative = ...
        (marketData.estimatedTotalCapacity ./ ...
         marketData.powerTurbine) .* ...
        marketData.production;

    totalGenerationForWeights = ...
        sum(totalGenerationByAlternative);

    if totalGenerationForWeights <= 0

        error( ...
            'Total generation is non-positive when computing remuneration.');
    end

    marketData.share_of_total_generation = ...
        totalGenerationByAlternative ./ ...
        totalGenerationForWeights;

    marketData.weighted_comp_share = ...
        marketData.share_of_total_generation .* ...
        compensationFactor;

    realCompensation = ...
        sum(marketData.weighted_comp_share) .* ...
        compensation;

    %% Annualization factor

    annualizationFactor = ...
        ( ...
            interestRate .* ...
            (1 + interestRate).^turbineLifetime ...
        ) ./ ...
        ( ...
            (1 + interestRate).^turbineLifetime - 1 ...
        );

    %% NPV-based producer surplus benchmark

    producerSurplusNpvBasedOneYear = ...
        sum( ...
            (marketData.estimatedTotalCapacity ./ ...
             marketData.powerTurbine) .* ...
            ( ...
                npvRevenuesTotalLifetime .* annualizationFactor - ...
                npvCostsTotalLifetime .* annualizationFactor ...
            ));

    %% Annual generation

    nTurbines = ...
        marketData.estimatedTotalCapacity ./ ...
        marketData.powerTurbine;

    annualGeneration = ...
        nTurbines .* ...
        marketData.production;

    totalGenerationAnnual = ...
        sum(annualGeneration);

    %% Subsidy expenditure

    subsidyOneYear = ...
        totalGenerationAnnual .* ...
        realCompensation;

    subsidyCheck = ...
        compensation .* ...
        sum(annualGeneration .* compensationFactor);

    subsidyDifference = ...
        subsidyOneYear - subsidyCheck;

    if abs(subsidyDifference) > ...
            max(1, 1e-10 .* abs(subsidyOneYear))

        warning([ ...
            'Production-weighted subsidy expenditure differs from the ', ...
            'direct alternative-level calculation by %.6f EUR/year.'], ...
            subsidyDifference);
    end

    %% Avoided variable gas and CO2 costs

    avoidVarCost_EURperMWh = ...
        76.38;

    generationMWh = ...
        totalGenerationAnnual ./ 1000;

    avoidedVarCostOneYear = ...
        generationMWh .* ...
        avoidVarCost_EURperMWh;

    %% Welfare and synthetic net-benefit measures

    % Resource-cost component:
    % PS_NPV - subsidy = negative annualized resource costs.
    resourceCostComponentOneYear = ...
        producerSurplusNpvBasedOneYear - ...
        subsidyOneYear;

    % Resource-cost-based welfare benchmark.
    resourceCostBasedNetWelfareOneYear = ...
        resourceCostComponentOneYear + ...
        avoidedVarCostOneYear;

    % Synthetic policy-evaluation measures are required only for the
    % reference-yield sensitivity analysis.
    if runReferenceYieldSensitivity

        syntheticCostComponentOneYear = ...
            producerSurplusProbabilityBasedOneYear - ...
            subsidyOneYear;

        probabilityBasedSyntheticNetBenefitOneYear = ...
            syntheticCostComponentOneYear + ...
            avoidedVarCostOneYear;

    else

        syntheticCostComponentOneYear = ...
            NaN;

        probabilityBasedSyntheticNetBenefitOneYear = ...
            NaN;
    end

    %% Diagnostics for s = 1 only

    diagnosticsAreValid = ...
        runBaselineDiagnostics && ...
        isfield(integrationDiagnostics, 'subsidyEquivalent') && ...
        isfield(integrationDiagnostics, 'normalizedSupply') && ...
        isfield(integrationDiagnostics, 'effectiveRemunerationGrid') && ...
        isfield(integrationDiagnostics, 'generationGrid') && ...
        isfinite(integrationDiagnostics.subsidyEquivalent) && ...
        integrationDiagnostics.subsidyEquivalent > 0 && ...
        ~isempty(integrationDiagnostics.normalizedSupply) && ...
        ~isempty(integrationDiagnostics.effectiveRemunerationGrid);

    if diagnosticsAreValid

        baselineDiagnostics = ...
            integrationDiagnostics;

        baselineDiagnostics.scaleRefYield = ...
            scaleRefYield;

        baselineDiagnostics.equilibriumCompensation = ...
            compensation;

        baselineDiagnostics.producerSurplusNpvBased = ...
            producerSurplusNpvBasedOneYear;

        baselineDiagnostics.producerSurplusProbabilityBased = ...
            producerSurplusProbabilityBasedOneYear;

        baselineDiagnostics.subsidyOneYear = ...
            subsidyOneYear;

        baselineDiagnostics.avoidedVarCostOneYear = ...
            avoidedVarCostOneYear;

        baselineDiagnostics.resourceCostBasedNetWelfare = ...
            resourceCostBasedNetWelfareOneYear;

        baselineDiagnostics.probabilityBasedSyntheticNetBenefit = ...
            probabilityBasedSyntheticNetBenefitOneYear;

        baselineDiagnostics.totalGenerationAnnual = ...
            totalGenerationAnnual;

        baselineDiagnostics.normalizedNpvSurplusHeight = ...
            producerSurplusNpvBasedOneYear ./ ...
            baselineDiagnostics.subsidyEquivalent;

        rhoSharesDiagnostic = ...
            [0; 0.25; 0.50; 0.75; 0.90; 0.95; 1.00];

        nrDiagnosticPoints = ...
            numel(rhoSharesDiagnostic);

        remunerationDiagnostic = ...
            rhoSharesDiagnostic .* ...
            compensation;

        meanAlternativeProbability = ...
            zeros(nrDiagnosticPoints, 1);

        meanNestProbability = ...
            zeros(nrDiagnosticPoints, 1);

        medianNestProbability = ...
            zeros(nrDiagnosticPoints, 1);

        p10NestProbability = ...
            zeros(nrDiagnosticPoints, 1);

        p90NestProbability = ...
            zeros(nrDiagnosticPoints, 1);

        medianUpperUtility = ...
            zeros(nrDiagnosticPoints, 1);

        p10UpperUtility = ...
            zeros(nrDiagnosticPoints, 1);

        p90UpperUtility = ...
            zeros(nrDiagnosticPoints, 1);

        regionRows = ...
            (1:nrAlt:height(marketData))';

        for kDiagnostic = 1:nrDiagnosticPoints

            rhoDiagnostic = ...
                remunerationDiagnostic(kDiagnostic);

            [alternativeProbabilityK, ...
             nestProbabilityK, ...
             zNestK] = ...
                calcNestedLogitProbabilitiesAtCompensation( ...
                    rhoDiagnostic, ...
                    marketData, ...
                    compensationFactor, ...
                    production, ...
                    turbineLifetime, ...
                    interestRate, ...
                    paraOPEXfix, ...
                    paraOPEXperkWhvar, ...
                    optsNpvAdjust, ...
                    explanatoryVariables, ...
                    powerPotential, ...
                    powerTurbine);

            meanAlternativeProbability(kDiagnostic) = ...
                mean(alternativeProbabilityK);

            nestProbabilityRegion = ...
                nestProbabilityK(regionRows);

            zNestRegion = ...
                zNestK(regionRows);

            meanNestProbability(kDiagnostic) = ...
                mean(nestProbabilityRegion);

            medianNestProbability(kDiagnostic) = ...
                median(nestProbabilityRegion);

            p10NestProbability(kDiagnostic) = ...
                prctile(nestProbabilityRegion, 10);

            p90NestProbability(kDiagnostic) = ...
                prctile(nestProbabilityRegion, 90);

            medianUpperUtility(kDiagnostic) = ...
                median(zNestRegion);

            p10UpperUtility(kDiagnostic) = ...
                prctile(zNestRegion, 10);

            p90UpperUtility(kDiagnostic) = ...
                prctile(zNestRegion, 90);
        end

        baselineDiagnostics.nestedLogitDiagnosticTable = ...
            table( ...
                rhoSharesDiagnostic, ...
                remunerationDiagnostic .* 100, ...
                meanAlternativeProbability, ...
                meanNestProbability, ...
                medianNestProbability, ...
                p10NestProbability, ...
                p90NestProbability, ...
                medianUpperUtility, ...
                p10UpperUtility, ...
                p90UpperUtility, ...
                'VariableNames', { ...
                    'ShareOfEquilibriumRemuneration', ...
                    'Remuneration_ctperkWh', ...
                    'MeanUnconditionalProbability', ...
                    'MeanInvestmentNestProbability', ...
                    'MedianInvestmentNestProbability', ...
                    'P10InvestmentNestProbability', ...
                    'P90InvestmentNestProbability', ...
                    'MedianUpperUtility', ...
                    'P10UpperUtility', ...
                    'P90UpperUtility'});

        fprintf( ...
            '\nNested-logit investment-response diagnostics for s = 1:\n');

        disp( ...
            baselineDiagnostics.nestedLogitDiagnosticTable);

        fprintf( ...
            '\nProbability-based producer-surplus diagnostics for s = 1:\n');

        fprintf( ...
            'Q(0) / Q(final):             %.8f\n', ...
            baselineDiagnostics.normalizedSupply(1));

        fprintf( ...
            'Final effective remuneration: %.4f ct/kWh\n', ...
            baselineDiagnostics.finalEffectiveRemuneration .* 100);
        
        fprintf( ...
            'Final synthetic generation:    %.4f TWh/year\n', ...
            baselineDiagnostics.finalGeneration ./ 1e9);
        
        fprintf( ...
            'Support-payment rectangle:     %.4f bn EUR/year\n', ...
            baselineDiagnostics.subsidyEquivalent ./ 1e9);
        
        fprintf( ...
            'Probability PS / support:      %.4f\n', ...
            baselineDiagnostics.producerSurplusTrapz ./ ...
            baselineDiagnostics.subsidyEquivalent);
        
        fprintf( ...
            'Probability-based PS:          %.4f bn EUR/year\n', ...
            baselineDiagnostics.producerSurplusTrapz ./ 1e9);

        fprintf( ...
            'Q(final) / Q(final):         %.8f\n', ...
            baselineDiagnostics.normalizedSupply(end));

        fprintf( ...
            'Probability PS / subsidy:    %.4f\n', ...
            baselineDiagnostics.producerSurplusTrapz ./ ...
            baselineDiagnostics.subsidyEquivalent);

        fprintf( ...
            'Integral using trapz:        %.4f bn EUR/year\n', ...
            baselineDiagnostics.producerSurplusTrapz ./ 1e9);

        fprintf( ...
            'Generation share using fallback: %.2f %%\n', ...
