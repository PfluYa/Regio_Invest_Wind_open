function [producerSurplusIntegralFleet, diagnostics] = ...
    calcIntegratedProducerSurplusFleet( ...
        marketData, ...
        totalCapacity, ...
        equilibriumCompensation, ...
        compensationFactor, ...
        production, ...
        turbineLifetime, ...
        interestRate, ...
        paraOPEXfix, ...
        paraOPEXperkWhvar, ...
        optsNpvAdjust, ...
        explanatoryVariables, ...
        powerPotential, ...
        powerTurbine, ...
        runDiagnostics)

    diagnostics = struct( ...
        'rhoGrid', [], ...
        'generationGrid', [], ...
        'weightedGenerationGrid', [], ...
        'effectiveRemunerationGrid', [], ...
        'normalizedSupply', [], ...
        'finalGeneration', NaN, ...
        'finalWeightedGeneration', NaN, ...
        'finalEffectiveRemuneration', NaN, ...
        'subsidyEquivalent', NaN, ...
        'producerSurplusTrapz', NaN, ...
        'diagnosticSupplyTable', table(), ...
        'fallbackGenerationShare', NaN);

    if equilibriumCompensation <= 0

        producerSurplusIntegralFleet = 0;
        return;
    end


    %% -------------------------------------------------------------
    % Probabilities at zero and equilibrium remuneration
    % -------------------------------------------------------------

    [probabilityZero, ...
     nestProbabilityZero] = ...
        calcNestedLogitProbabilitiesAtCompensation( ...
            0, ...
            marketData, ...
            compensationFactor, ...
            production, ...
            turbineLifetime, ...
            interestRate, ...
            paraOPEXfix, ...
            paraOPEXperkWhvar, ...
            optsNpvAdjust, ...
            explanatoryVariables, ...
            powerPotential, ...
            powerTurbine);

    [probabilityEquilibrium, ...
     nestProbabilityEquilibrium] = ...
        calcNestedLogitProbabilitiesAtCompensation( ...
            equilibriumCompensation, ...
            marketData, ...
            compensationFactor, ...
            production, ...
            turbineLifetime, ...
            interestRate, ...
            paraOPEXfix, ...
            paraOPEXperkWhvar, ...
            optsNpvAdjust, ...
            explanatoryVariables, ...
            powerPotential, ...
            powerTurbine);


    probabilityChange = ...
        probabilityEquilibrium - probabilityZero;

    nestProbabilityChange = ...
        nestProbabilityEquilibrium - nestProbabilityZero;


    %% -------------------------------------------------------------
    % Annual generation of the equilibrium fleet
    % -------------------------------------------------------------

    yieldPerCapacity = ...
        production ./ powerTurbine;

    equilibriumGenerationByAlternative = ...
        totalCapacity .* yieldPerCapacity;

    equilibriumGeneration = ...
        sum(equilibriumGenerationByAlternative);

    if equilibriumGeneration <= 0

        producerSurplusIntegralFleet = 0;
        return;
    end

    generationWeights = ...
        equilibriumGenerationByAlternative ./ equilibriumGeneration;


    %% -------------------------------------------------------------
    % Check alternative-specific probability responses
    % -------------------------------------------------------------

    probabilityTolerance = 1e-10;
    monotonicityTolerance = 1e-8;

    nrCheckPoints = 9;

    rhoCheckGrid = ...
        linspace( ...
            0, ...
            equilibriumCompensation, ...
            nrCheckPoints);

    probabilityCheck = ...
        zeros( ...
            height(marketData), ...
            nrCheckPoints);

    for kCheck = 1:nrCheckPoints

        probabilityCheck(:, kCheck) = ...
            calcNestedLogitProbabilitiesAtCompensation( ...
                rhoCheckGrid(kCheck), ...
                marketData, ...
                compensationFactor, ...
                production, ...
                turbineLifetime, ...
                interestRate, ...
                paraOPEXfix, ...
                paraOPEXperkWhvar, ...
                optsNpvAdjust, ...
                explanatoryVariables, ...
                powerPotential, ...
                powerTurbine);
    end

    isMonotoneAlternative = ...
        all( ...
            diff(probabilityCheck, 1, 2) >= ...
            -monotonicityTolerance, ...
            2);

    activeCapacity = ...
        totalCapacity > 0;

    validAlternativeResponse = ...
        activeCapacity & ...
        probabilityChange > probabilityTolerance & ...
        isMonotoneAlternative;


    %% -------------------------------------------------------------
    % Nest response as fallback
    % -------------------------------------------------------------

    validNestResponse = ...
        nestProbabilityChange > probabilityTolerance;

    nationalNestProbabilityZero = ...
        sum( ...
            generationWeights .* ...
            nestProbabilityZero);

    nationalNestProbabilityEquilibrium = ...
        sum( ...
            generationWeights .* ...
            nestProbabilityEquilibrium);

    nationalNestProbabilityChange = ...
        nationalNestProbabilityEquilibrium - ...
        nationalNestProbabilityZero;

    useLinearNationalFallback = ...
        nationalNestProbabilityChange <= probabilityTolerance;


    %% -------------------------------------------------------------
    % Report share of equilibrium generation using fallback
    % -------------------------------------------------------------

    if equilibriumGeneration > 0

        fallbackGenerationShare = ...
            sum( ...
                equilibriumGenerationByAlternative( ...
                    activeCapacity & ~validAlternativeResponse)) ./ ...
            equilibriumGeneration;

    else

        fallbackGenerationShare = 0;
    end

    if runDiagnostics && fallbackGenerationShare > 0

        fprintf( ...
            ['Generation share using nest-response fallback: ', ...
             '%.2f %%\n'], ...
            100 .* fallbackGenerationShare);
    end


    %% -------------------------------------------------------------
    % Construct remuneration path
    % -------------------------------------------------------------

    nrIntegrationPoints = 501;

    rhoGrid = ...
        linspace( ...
            0, ...
            equilibriumCompensation, ...
            nrIntegrationPoints)';

    generationGrid = ...
        zeros(nrIntegrationPoints, 1);

    weightedGenerationGrid = ...
        zeros(nrIntegrationPoints, 1);

    effectiveRemunerationGrid = ...
        zeros(nrIntegrationPoints, 1);


    for kGrid = 1:nrIntegrationPoints

        [generationGrid(kGrid), ...
         effectiveRemunerationGrid(kGrid), ...
         weightedGenerationGrid(kGrid)] = ...
            calcTotalFleetSupplyPoint( ...
                rhoGrid(kGrid), ...
                equilibriumCompensation, ...
                probabilityZero, ...
                probabilityChange, ...
                validAlternativeResponse, ...
                nestProbabilityZero, ...
                nestProbabilityChange, ...
                validNestResponse, ...
                generationWeights, ...
                nationalNestProbabilityZero, ...
                nationalNestProbabilityChange, ...
                useLinearNationalFallback, ...
                marketData, ...
                equilibriumGenerationByAlternative, ...
                compensationFactor, ...
                production, ...
                turbineLifetime, ...
                interestRate, ...
                paraOPEXfix, ...
                paraOPEXperkWhvar, ...
                optsNpvAdjust, ...
                explanatoryVariables, ...
                powerPotential, ...
                powerTurbine);
    end


    %% -------------------------------------------------------------
    % Check effective-remuneration path
    % -------------------------------------------------------------
    
    if any(diff(effectiveRemunerationGrid) < -1e-1)
    
        error( ...
            'Effective-remuneration path is unexpectedly non-monotonic.');
    end

    %% -------------------------------------------------------------
    % Probability-based producer surplus
    %
    % For every counterfactual base-remuneration level rho, the synthetic
    % fleet is first mapped into its production-weighted effective
    % remuneration rho_eff(rho,s). Producer surplus is then defined as the
    % area under synthetic generation in effective-remuneration space:
    %
    % PS_prob(s) = integral Q(rho,s) d rho_eff(rho,s)
    %
    % This is a behaviorally based synthetic surplus measure and should not
    % be interpreted as an exact money-metric welfare measure.
    % -------------------------------------------------------------

    producerSurplusIntegralFleet = ...
        trapz( ...
            effectiveRemunerationGrid, ...
            generationGrid);

    if ~isfinite(producerSurplusIntegralFleet)

        error( ...
            'Probability-based producer surplus is not finite.');
    end


    %% -------------------------------------------------------------
    % Equilibrium consistency checks
    % -------------------------------------------------------------

    finalGeneration = ...
        generationGrid(end);

    finalWeightedGeneration = ...
        weightedGenerationGrid(end);

    finalEffectiveRemuneration = ...
        effectiveRemunerationGrid(end);


    expectedFinalEffectiveRemuneration = ...
        equilibriumCompensation .* ...
        sum( ...
            equilibriumGenerationByAlternative .* ...
            compensationFactor) ./ ...
        equilibriumGeneration;


    relativeGenerationDifference = ...
        abs( ...
            finalGeneration - equilibriumGeneration) ./ ...
        max(1, abs(equilibriumGeneration));

    relativeRemunerationDifference = ...
        abs( ...
            finalEffectiveRemuneration - ...
            expectedFinalEffectiveRemuneration) ./ ...
        max( ...
            1e-12, ...
            abs(expectedFinalEffectiveRemuneration));


    if relativeGenerationDifference > 1e-8

        warning( ...
            ['Final synthetic generation differs from equilibrium ', ...
             'fleet generation by %.3e.'], ...
            relativeGenerationDifference);
    end

    if relativeRemunerationDifference > 1e-8

        warning( ...
            ['Final effective remuneration differs from the direct ', ...
             'equilibrium calculation by %.3e.'], ...
            relativeRemunerationDifference);
    end


    %% -------------------------------------------------------------
    % Diagnostics for Appendix-E figure
    % -------------------------------------------------------------

    normalizedSupply = ...
        generationGrid ./ finalGeneration;

    subsidyEquivalent = ...
        finalEffectiveRemuneration .* finalGeneration;

    producerSurplusTrapz = ...
        producerSurplusIntegralFleet;


    diagnostics.rhoGrid = ...
        rhoGrid;

    diagnostics.generationGrid = ...
        generationGrid;

    diagnostics.weightedGenerationGrid = ...
        weightedGenerationGrid;

    diagnostics.effectiveRemunerationGrid = ...
        effectiveRemunerationGrid;

    diagnostics.normalizedSupply = ...
        normalizedSupply;

    diagnostics.finalGeneration = ...
        finalGeneration;

    diagnostics.finalWeightedGeneration = ...
        finalWeightedGeneration;

    diagnostics.finalEffectiveRemuneration = ...
        finalEffectiveRemuneration;

    diagnostics.subsidyEquivalent = ...
        subsidyEquivalent;

    diagnostics.producerSurplusTrapz = ...
        producerSurplusTrapz;

    diagnostics.fallbackGenerationShare = ...
        fallbackGenerationShare;


    if runDiagnostics

        relativeEffectiveRemunerationGrid = ...
            effectiveRemunerationGrid ./ ...
            finalEffectiveRemuneration;

        evaluationPoints = ...
            [0.25; 0.50; 0.75; 0.90; 0.95; 1.00];

        normalizedSupplyAtPoints = ...
            interp1( ...
                relativeEffectiveRemunerationGrid, ...
                normalizedSupply, ...
                evaluationPoints, ...
                'linear', ...
                'extrap');

        diagnostics.diagnosticSupplyTable = ...
            table( ...
                evaluationPoints, ...
                normalizedSupplyAtPoints, ...
                'VariableNames', { ...
                    'ShareOfEquilibriumEffectiveRemuneration', ...
                    'ShareOfFinalSyntheticSupply'});
    end
end


%% ========================================================================
% LOCAL FUNCTION: SYNTHETIC SUPPLY POINT OF TOTAL FLEET
% ========================================================================

function [syntheticGeneration, ...
          effectiveRemuneration, ...
          weightedSyntheticGeneration] = ...
    calcTotalFleetSupplyPoint( ...
        rho, ...
        equilibriumCompensation, ...
        probabilityZero, ...
        probabilityChange, ...
        validAlternativeResponse, ...
        nestProbabilityZero, ...
        nestProbabilityChange, ...
        validNestResponse, ...
        generationWeights, ...
        nationalNestProbabilityZero, ...
        nationalNestProbabilityChange, ...
        useLinearNationalFallback, ...
        marketData, ...
        equilibriumGenerationByAlternative, ...
        compensationFactor, ...
        production, ...
        turbineLifetime, ...
        interestRate, ...
        paraOPEXfix, ...
        paraOPEXperkWhvar, ...
        optsNpvAdjust, ...
        explanatoryVariables, ...
        powerPotential, ...
        powerTurbine)

    [probabilityAtRho, ...
     nestProbabilityAtRho] = ...
        calcNestedLogitProbabilitiesAtCompensation( ...
            rho, ...
            marketData, ...
            compensationFactor, ...
            production, ...
            turbineLifetime, ...
            interestRate, ...
            paraOPEXfix, ...
            paraOPEXperkWhvar, ...
            optsNpvAdjust, ...
            explanatoryVariables, ...
            powerPotential, ...
            powerTurbine);


    %% -------------------------------------------------------------
    % National fallback response
    % -------------------------------------------------------------

    if useLinearNationalFallback

        nationalRelativeResponse = ...
            rho ./ equilibriumCompensation;

    else

        nationalNestProbabilityAtRho = ...
            sum( ...
                generationWeights .* ...
                nestProbabilityAtRho);

        nationalRelativeResponse = ...
            ( ...
                nationalNestProbabilityAtRho - ...
                nationalNestProbabilityZero ...
            ) ./ ...
            nationalNestProbabilityChange;
    end

    nationalRelativeResponse = ...
        max( ...
            0, ...
            min(1, nationalRelativeResponse));


    %% -------------------------------------------------------------
    % Regional nest response
    % -------------------------------------------------------------

    relativeNestResponse = ...
        nationalRelativeResponse .* ...
        ones(size(nestProbabilityAtRho));

    relativeNestResponse(validNestResponse) = ...
        ( ...
            nestProbabilityAtRho(validNestResponse) - ...
            nestProbabilityZero(validNestResponse) ...
        ) ./ ...
        nestProbabilityChange(validNestResponse);

    relativeNestResponse = ...
        max( ...
            0, ...
            min(1, relativeNestResponse));


    %% -------------------------------------------------------------
    % Alternative-specific response
    % -------------------------------------------------------------

    relativeResponse = ...
        relativeNestResponse;

    relativeResponse(validAlternativeResponse) = ...
        ( ...
            probabilityAtRho(validAlternativeResponse) - ...
            probabilityZero(validAlternativeResponse) ...
        ) ./ ...
        probabilityChange(validAlternativeResponse);

    relativeResponse = ...
        max( ...
            0, ...
            min(1, relativeResponse));


    %% -------------------------------------------------------------
    % Synthetic generation of total equilibrium fleet
    % -------------------------------------------------------------

    syntheticGenerationByAlternative = ...
        equilibriumGenerationByAlternative .* ...
        relativeResponse;

    syntheticGeneration = ...
        sum(syntheticGenerationByAlternative);

    weightedSyntheticGeneration = ...
        sum( ...
            syntheticGenerationByAlternative .* ...
            compensationFactor);


    %% -------------------------------------------------------------
    % Production-weighted effective remuneration of the synthetic fleet
    % (used for diagnostics and the Appendix-E figure)
    % -------------------------------------------------------------

    if syntheticGeneration > 0

        effectiveRemuneration = ...
            rho .* ...
            weightedSyntheticGeneration ./ ...
            syntheticGeneration;

    else

        effectiveRemuneration = 0;
    end


    if ~isfinite(syntheticGeneration) || ...
            ~isfinite(weightedSyntheticGeneration) || ...
            ~isfinite(effectiveRemuneration)

        error([ ...
            'Non-finite synthetic supply point at ', ...
            'rho = %.8f EUR/kWh.'], ...
            rho);
    end
end