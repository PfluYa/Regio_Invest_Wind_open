%% ========================================================================
% LOCAL FUNCTION: INVESTMENT LOOP
% ========================================================================

function [estimatedNewCap, ...
          compensation, ...
          installedCapacity, ...
          totalGenerationAnnual, ...
          countWhile, ...
          npv, ...
          npvCostsTotalLifetime, ...
          npvRevenuesTotalLifetime] = ...
    runInvestmentLoop( ...
        marketData, ...
        production, ...
        turbineLifetime, ...
        interestRate, ...
        compensation, ...
        compensationFactor, ...
        paraOPEXfix, ...
        paraOPEXperkWhvar, ...
        optsNpvAdjust, ...
        explanatoryVariables, ...
        powerPotential, ...
        powerPotentialInvest, ...
        powerTurbine, ...
        investFactor, ...
        availableSpace, ...
        iterationLogicInvestment, ...
        targetCapacityWind, ...
        targetEnergyProduction, ...
        tolEnergy)

    maxIter = ...
        100000;

    countWhile = ...
        0;

    estimatedNewCap = ...
        zeros(height(marketData), 1);

    function generation = ...
            computeAnnualGeneration(totalCapacity)

        numberOfTurbines = ...
            totalCapacity ./ ...
            powerTurbine;

        generation = ...
            sum( ...
                numberOfTurbines .* ...
                marketData.production);
    end

    function [newCapacityEval, ...
              installedCapacityEval, ...
              generationEval, ...
              npvEval, ...
              costsEval, ...
              revenuesEval] = ...
            evaluateAtCompensation(compensationEval)

        [npvEval, ...
         costsEval, ...
         revenuesEval] = ...
            calcNetPresentValue( ...
                marketData.investCost, ...
                production, ...
                turbineLifetime, ...
                interestRate, ...
                compensationEval, ...
                compensationFactor, ...
                paraOPEXfix, ...
                paraOPEXperkWhvar);

        switch optsNpvAdjust

            case 'NPVperInvestCosts'

                npvAdjustedEval = ...
                    npvEval ./ ...
                    marketData.investCost;

            case 'NPVperArea'

                npvAdjustedEval = ...
                    npvEval ./ ...
                    (powerTurbine ./ powerPotential);

            case 'none'

                npvAdjustedEval = ...
                    npvEval;

            otherwise

                error('Invalid optsNpvAdjust value.');
        end

        npvTransformedEval = ...
            transformNPV(npvAdjustedEval);

        explanatoryMatrixEval = ...
            zeros( ...
                height(marketData), ...
                numel(explanatoryVariables));

        explanatoryMatrixEval(:,1) = ...
            npvTransformedEval;

        if numel(explanatoryVariables) > 1

            explanatoryMatrixEval(:,2:end) = ...
                marketData{:, explanatoryVariables(2:end)};
        end

        predictedMarketShareEval = ...
            binomNestLog(explanatoryMatrixEval);

        newCapacityEval = ...
            floor( ...
                investFactor .* ...
                availableSpace .* ...
                powerPotentialInvest ./ ...
                powerTurbine .* ...
                predictedMarketShareEval ...
            ) .* ...
            powerTurbine;

        totalCapacityEval = ...
            newCapacityEval + ...
            marketData.capacitiesInSimYear;

        installedCapacityEval = ...
            sum(totalCapacityEval);

        generationEval = ...
            computeAnnualGeneration(totalCapacityEval);
    end


    if strcmp(iterationLogicInvestment, 'capacity')

        installedCapacity = ...
            sum(marketData.capacitiesInSimYear);

        totalGenerationAnnual = ...
            computeAnnualGeneration( ...
                marketData.capacitiesInSimYear);

        bestRelativeError = ...
            inf;

        bestCompensation = ...
            compensation;

        bestEstimatedNewCap = ...
            estimatedNewCap;

        bestInstalledCapacity = ...
            installedCapacity;

        bestGeneration = ...
            totalGenerationAnnual;

        while countWhile < maxIter

            [newCapacityCurrent, ...
             installedCapacityCurrent, ...
             generationCurrent, ...
             npvCurrent, ...
             costsCurrent, ...
             revenuesCurrent] = ...
                evaluateAtCompensation(compensation);

            relativeError = ...
                abs( ...
                    installedCapacityCurrent - ...
                    targetCapacityWind ...
                ) ./ ...
                targetCapacityWind;

            if relativeError < bestRelativeError

                bestRelativeError = ...
                    relativeError;

                bestCompensation = ...
                    compensation;

                bestEstimatedNewCap = ...
                    newCapacityCurrent;

                bestInstalledCapacity = ...
                    installedCapacityCurrent;

                bestGeneration = ...
                    generationCurrent;

                npv = ...
                    npvCurrent;

                npvCostsTotalLifetime = ...
                    costsCurrent;

                npvRevenuesTotalLifetime = ...
                    revenuesCurrent;
            end

            withinTargetInterval = ...
                installedCapacityCurrent > ...
                targetCapacityWind && ...
                installedCapacityCurrent ./ ...
                targetCapacityWind <= ...
                (1 + tolEnergy);

            if withinTargetInterval

                bestCompensation = ...
                    compensation;

                bestEstimatedNewCap = ...
                    newCapacityCurrent;

                bestInstalledCapacity = ...
                    installedCapacityCurrent;

                bestGeneration = ...
                    generationCurrent;

                npv = ...
                    npvCurrent;

                npvCostsTotalLifetime = ...
                    costsCurrent;

                npvRevenuesTotalLifetime = ...
                    revenuesCurrent;

                break;
            end

            if installedCapacityCurrent ./ ...
                    targetCapacityWind > ...
                    (1 + tolEnergy)

                compensation = ...
                    compensation - 0.00005;

            else

                compensation = ...
                    compensation + 0.001;
            end

            countWhile = ...
                countWhile + 1;
        end

        compensation = ...
            bestCompensation;

        estimatedNewCap = ...
            bestEstimatedNewCap;

        installedCapacity = ...
            bestInstalledCapacity;

        totalGenerationAnnual = ...
            bestGeneration;

        if countWhile >= maxIter

            warning([ ...
                'Capacity calibration reached maxIter. Returning the ', ...
                'closest observed result with relative error %.4f%%.'], ...
                100 .* bestRelativeError);
        end

    elseif strcmp(iterationLogicInvestment, 'energy')

        if ~isfinite(targetEnergyProduction) || ...
                targetEnergyProduction <= 0

            error([ ...
                'targetEnergyProduction must be a finite positive value.']);
        end

        baselineGeneration = ...
            computeAnnualGeneration( ...
                marketData.capacitiesInSimYear);

        if baselineGeneration >= targetEnergyProduction

            warning([ ...
                'Existing generation already reaches the energy target. ', ...
                'Returning zero new investment and zero remuneration.']);

            compensation = ...
                0;

            estimatedNewCap = ...
                zeros(height(marketData), 1);

            installedCapacity = ...
                sum(marketData.capacitiesInSimYear);

            totalGenerationAnnual = ...
                baselineGeneration;

            [npv, ...
             npvCostsTotalLifetime, ...
             npvRevenuesTotalLifetime] = ...
                calcNetPresentValue( ...
                    marketData.investCost, ...
                    production, ...
                    turbineLifetime, ...
                    interestRate, ...
                    compensation, ...
                    compensationFactor, ...
                    paraOPEXfix, ...
                    paraOPEXperkWhvar);

            return;
        end

        compensationLower = ...
            0;

        compensationUpper = ...
            max(0.20, 2 .* max(compensation, 0.01));

        maximumCompensation = ...
            1.0;

        maxBisectionIter = ...
            80;

        bestRelativeError = ...
            inf;

        bestCompensation = ...
            compensation;

        bestEstimatedNewCap = ...
            estimatedNewCap;

        bestInstalledCapacity = ...
            sum(marketData.capacitiesInSimYear);

        bestGeneration = ...
            baselineGeneration;

        [~, ...
         ~, ...
         generationUpper] = ...
            evaluateAtCompensation(compensationUpper);

        while generationUpper < targetEnergyProduction && ...
                compensationUpper < maximumCompensation

            compensationUpper = ...
                min( ...
                    maximumCompensation, ...
                    2 .* compensationUpper);

            [~, ...
             ~, ...
             generationUpper] = ...
                evaluateAtCompensation(compensationUpper);
        end

        if generationUpper < targetEnergyProduction

            error([ ...
                'The energy target cannot be reached within the tested ', ...
                'remuneration range.']);
        end

        for iteration = 1:maxBisectionIter

            countWhile = ...
                iteration;

            compensationMid = ...
                0.5 .* ...
                (compensationLower + compensationUpper);

            [newCapacityMid, ...
             installedCapacityMid, ...
             generationMid, ...
             npvMid, ...
             costsMid, ...
             revenuesMid] = ...
                evaluateAtCompensation(compensationMid);

            relativeError = ...
                abs( ...
                    generationMid - ...
                    targetEnergyProduction ...
                ) ./ ...
                targetEnergyProduction;

            if relativeError < bestRelativeError

                bestRelativeError = ...
                    relativeError;

                bestCompensation = ...
                    compensationMid;

                bestEstimatedNewCap = ...
                    newCapacityMid;

                bestInstalledCapacity = ...
                    installedCapacityMid;

                bestGeneration = ...
                    generationMid;

                npv = ...
                    npvMid;

                npvCostsTotalLifetime = ...
                    costsMid;

                npvRevenuesTotalLifetime = ...
                    revenuesMid;
            end

            if relativeError <= tolEnergy

                break;
            end

            if generationMid < targetEnergyProduction

                compensationLower = ...
                    compensationMid;

            else

                compensationUpper = ...
                    compensationMid;
            end

            if compensationUpper - compensationLower < 1e-10

                break;
            end
        end

        compensation = ...
            bestCompensation;

        estimatedNewCap = ...
            bestEstimatedNewCap;

        installedCapacity = ...
            bestInstalledCapacity;

        totalGenerationAnnual = ...
            bestGeneration;

        if bestRelativeError > tolEnergy

            warning([ ...
                'The energy tolerance could not be reached. Returning ', ...
                'the closest discrete solution with relative error %.4f%%.'], ...
                100 .* bestRelativeError);
        end

    else

        error([ ...
            'Unknown iterationLogicInvestment. ', ...
            'Use ''capacity'' or ''energy''.']);
    end

    [npv, ...
     npvCostsTotalLifetime, ...
     npvRevenuesTotalLifetime] = ...
        calcNetPresentValue( ...
            marketData.investCost, ...
            production, ...
            turbineLifetime, ...
            interestRate, ...
            compensation, ...
            compensationFactor, ...
            paraOPEXfix, ...
            paraOPEXperkWhvar);
end


