% LOCAL FUNCTION: NESTED LOGIT
% ========================================================================

function [y, propNest, propAlternative, zNest] = ...
    binomNestLog(x)

    global beta alpha gamma lambda nrAlt nrDecisionMaker

    utilityScaled = ...
        (sum(x .* beta, 2) + alpha) ./ ...
        lambda;

    utilityMatrix = ...
        reshape( ...
            utilityScaled, ...
            [nrAlt, nrDecisionMaker]);

    maxUtilityByRegion = ...
        max(utilityMatrix, [], 1);

    stabilizedUtilityMatrix = ...
        utilityMatrix - ...
        maxUtilityByRegion;

    expUtilityMatrix = ...
        exp(stabilizedUtilityMatrix);

    denominatorByRegion = ...
        sum(expUtilityMatrix, 1);

    propAlternativeMatrix = ...
        expUtilityMatrix ./ ...
        denominatorByRegion;

    propAlternative = ...
        propAlternativeMatrix(:);

    inclusiveValueByRegion = ...
        maxUtilityByRegion + ...
        log(denominatorByRegion);

    inclusiveValue = ...
        repelem( ...
            inclusiveValueByRegion, ...
            nrAlt)';

    zNest = ...
        gamma + ...
        lambda .* inclusiveValue;

    propNest = ...
        zeros(size(zNest));

    positiveIndex = ...
        zNest >= 0;

    propNest(positiveIndex) = ...
        1 ./ ...
        (1 + exp(-zNest(positiveIndex)));

    expNegativeZ = ...
        exp(zNest(~positiveIndex));

    propNest(~positiveIndex) = ...
        expNegativeZ ./ ...
        (1 + expNegativeZ);

    y = ...
        propNest .* ...
        propAlternative;
end


