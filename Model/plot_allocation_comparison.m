%% FIGURE 4: COMPARISON OF ALLOCATION STRATEGIES BY FEDERAL STATE
% Comparison of total installed wind capacity in 2040 under:
%   Case A - choice-based investment via nested logit
%   Case B - proportional allocation to remaining available land
%   Case C - merit-order allocation based on NPV
%
% The national capacity target is held fixed across all three cases.
% Capacities are aggregated from NUTS3 regions to German federal states
% using the first three characters of the NUTS code (NUTS1).
%
% Output:
%   Results Paper/Figure_4_allocation_comparison.pdf

scriptPath = ...
    mfilename('fullpath');

scriptFolder = ...
    fileparts(scriptPath);

repoFolder = ...
    fileparts(scriptFolder);

resultsFolder = ...
    fullfile(repoFolder, 'Results Paper');


%% ------------------------------------------------------------------------
% 1. INPUT FILES
% -------------------------------------------------------------------------

fileCaseA = ...
    fullfile( ...
        resultsFolder, ...
        'results_nuts3_base2024_target2040_expCase1_capacity.mat');

fileCaseB = ...
    fullfile( ...
        resultsFolder, ...
        'results_nuts3_base2024_target2040_expCase3_capacity.mat');

fileCaseC = ...
    fullfile( ...
        resultsFolder, ...
        'results_nuts3_base2024_target2040_expCase4_capacity.mat');

requiredFiles = ...
    {fileCaseA, fileCaseB, fileCaseC};

for iFile = 1:numel(requiredFiles)

    if ~isfile(requiredFiles{iFile})

        error( ...
            'Required 2040 result file not found: %s', ...
            requiredFiles{iFile});
    end
end


%% ------------------------------------------------------------------------
% 2. LOAD REGIONAL RESULTS
% -------------------------------------------------------------------------

S_A = ...
    load(fileCaseA, 'selected_data');

S_B = ...
    load(fileCaseB, 'selected_data');

S_C = ...
    load(fileCaseC, 'selected_data');

dataA = ...
    S_A.selected_data;

dataB = ...
    alignToReference( ...
        S_B.selected_data, ...
        dataA);

dataC = ...
    alignToReference( ...
        S_C.selected_data, ...
        dataA);


%% ------------------------------------------------------------------------
% 3. AGGREGATE NUTS3 RESULTS TO FEDERAL STATES
% -------------------------------------------------------------------------

stateCodes = ...
    ["DE1"; "DE2"; "DE4"; "DE7"; "DE8"; "DE9"; ...
     "DEA"; "DEB"; "DEC"; "DED"; "DEE"; "DEF"; "DEG"];

stateNames = ...
    ["Baden-Wuerttemberg"; ...
     "Bavaria"; ...
     "Brandenburg"; ...
     "Hesse"; ...
     "Mecklenburg-Vorpommern"; ...
     "Lower Saxony"; ...
     "North Rhine-Westphalia"; ...
     "Rhineland-Palatinate"; ...
     "Saarland"; ...
     "Saxony"; ...
     "Saxony-Anhalt"; ...
     "Schleswig-Holstein"; ...
     "Thuringia"];

% City states (Berlin, Bremen, Hamburg) are omitted from the plotted bars,
% matching the presentation in the paper. Their capacity remains part of
% the national totals.

capacityA = ...
    aggregateCapacityByState( ...
        dataA, ...
        stateCodes);

capacityB = ...
    aggregateCapacityByState( ...
        dataB, ...
        stateCodes);

capacityC = ...
    aggregateCapacityByState( ...
        dataC, ...
        stateCodes);

stateCapacityTable = ...
    table( ...
        stateCodes, ...
        stateNames, ...
        capacityA, ...
        capacityB, ...
        capacityC, ...
        'VariableNames', { ...
            'NUTS1', ...
            'FederalState', ...
            'CaseA_GW', ...
            'CaseB_GW', ...
            'CaseC_GW'});

fprintf('\n');
fprintf('============================================================\n');
fprintf('FIGURE 4: INSTALLED CAPACITY BY FEDERAL STATE [GW]\n');
fprintf('============================================================\n\n');

disp(stateCapacityTable);

figure4DataCsv = ...
    fullfile( ...
        resultsFolder, ...
        'Figure_4_allocation_comparison_data.csv');

figure4DataMat = ...
    fullfile( ...
        resultsFolder, ...
        'Figure_4_allocation_comparison_data.mat');

writetable( ...
    stateCapacityTable, ...
    figure4DataCsv);

save( ...
    figure4DataMat, ...
    'stateCapacityTable');


%% ------------------------------------------------------------------------
% 4. BUILD FEDERAL-STATE OUTLINES
% -------------------------------------------------------------------------

nStates = ...
    numel(stateCodes);

stateShapes = ...
    cell(nStates, 1);

stateCentroids = ...
    zeros(nStates, 2);

nutsID = ...
    string(dataA.nutsID);

nuts1 = ...
    extractBetween( ...
        nutsID, ...
        1, ...
        3);

for iState = 1:nStates

    idxState = ...
        nuts1 == stateCodes(iState);

    if ~any(idxState)

        error( ...
            'No NUTS3 regions found for federal state %s.', ...
            stateCodes(iState));
    end

    stateShapes{iState} = ...
        combineRegionalPolygons( ...
            dataA.lonPoly(idxState), ...
            dataA.latPoly(idxState));

    [centroidX, centroidY] = ...
        centroid(stateShapes{iState});

    stateCentroids(iState, :) = ...
        [centroidX, centroidY];
end


%% ------------------------------------------------------------------------
% 5. PLOT SETTINGS
% -------------------------------------------------------------------------

% Colors reproduce the light-to-dark ordering of Cases A-C in the paper.
colorCaseA = ...
    [0.35 0.78 0.93];

colorCaseB = ...
    [0.10 0.45 0.60];

colorCaseC = ...
    [0.08 0.13 0.16];

mapEdgeColor = ...
    [0.25 0.25 0.25];

barEdgeColor = ...
    [0.15 0.15 0.15];

barWidth = ...
    0.28;

barGap = ...
    0.03;

% Convert GW into latitude degrees for the map overlay.
% A value around 75 GW then produces a bar of roughly 1.8 degrees.
barHeightScale = ...
    0.024;

labelOffset = ...
    0.15;

% Manual offsets improve readability where federal-state centroids are
% close to one another. Order follows stateCodes above.
anchorOffset = [ ...
     0.00,  0.00; ... % DE1 Baden-Wuerttemberg
     0.15, -0.05; ... % DE2 Bavaria
     0.10,  0.05; ... % DE4 Brandenburg
     0.00,  0.00; ... % DE7 Hesse
     0.25,  0.05; ... % DE8 Mecklenburg-Vorpommern
    -0.10,  0.05; ... % DE9 Lower Saxony
    -0.15,  0.00; ... % DEA North Rhine-Westphalia
    -0.05, -0.05; ... % DEB Rhineland-Palatinate
    -0.10, -0.05; ... % DEC Saarland
     0.25,  0.00; ... % DED Saxony
    -0.05,  0.10; ... % DEE Saxony-Anhalt
     0.00,  0.10; ... % DEF Schleswig-Holstein
     0.10,  0.00  ... % DEG Thuringia
    ];


%% ------------------------------------------------------------------------
% 6. CREATE MAP AND BAR OVERLAYS
% -------------------------------------------------------------------------

fig = ...
    figure( ...
        'Position', ...
        [160 80 820 920], ...
        'Color', ...
        'w');

ax = ...
    axes(fig);

hold(ax, 'on');

% Federal-state outlines
for iState = 1:nStates

    plot( ...
        ax, ...
        stateShapes{iState}, ...
        'FaceColor', ...
        'none', ...
        'EdgeColor', ...
        mapEdgeColor, ...
        'LineWidth', ...
        0.8);
end

% City-state outlines are retained in the map even though no bars are
% displayed for them.
cityStateCodes = ...
    ["DE3"; "DE5"; "DE6"];

for iCity = 1:numel(cityStateCodes)

    idxCity = ...
        nuts1 == cityStateCodes(iCity);

    if any(idxCity)

        cityShape = ...
            combineRegionalPolygons( ...
                dataA.lonPoly(idxCity), ...
                dataA.latPoly(idxCity));

        plot( ...
            ax, ...
            cityShape, ...
            'FaceColor', ...
            'none', ...
            'EdgeColor', ...
            mapEdgeColor, ...
            'LineWidth', ...
            0.8);
    end
end

% Bar clusters
for iState = 1:nStates

    anchorX = ...
        stateCentroids(iState, 1) + ...
        anchorOffset(iState, 1);

    baselineY = ...
        stateCentroids(iState, 2) + ...
        anchorOffset(iState, 2);

    valuesGW = ...
        [ ...
            capacityA(iState), ...
            capacityB(iState), ...
            capacityC(iState) ...
        ];

    colors = ...
        [ ...
            colorCaseA; ...
            colorCaseB; ...
            colorCaseC ...
        ];

    clusterWidth = ...
        3 .* barWidth + ...
        2 .* barGap;

    xLeft = ...
        anchorX - ...
        clusterWidth ./ 2;

    % Baseline
    plot( ...
        ax, ...
        [xLeft - 0.04, xLeft + clusterWidth + 0.04], ...
        [baselineY, baselineY], ...
        '-', ...
        'Color', ...
        barEdgeColor, ...
        'LineWidth', ...
        0.7);

    for iCase = 1:3

        x0 = ...
            xLeft + ...
            (iCase - 1) .* ...
            (barWidth + barGap);

        barHeight = ...
            valuesGW(iCase) .* ...
            barHeightScale;

        patch( ...
            ax, ...
            [x0, x0 + barWidth, x0 + barWidth, x0], ...
            [baselineY, baselineY, baselineY + barHeight, baselineY + barHeight], ...
            colors(iCase, :), ...
            'EdgeColor', ...
            barEdgeColor, ...
            'LineWidth', ...
            0.45);

        text( ...
            ax, ...
            x0 + barWidth ./ 2, ...
            baselineY - labelOffset, ...
            sprintf('%.1f', valuesGW(iCase)), ...
            'HorizontalAlignment', ...
            'center', ...
            'VerticalAlignment', ...
            'top', ...
            'FontSize', ...
            7.5, ...
            'Color', ...
            [0.15 0.15 0.15]);
    end
end


%% ------------------------------------------------------------------------
% 7. LEGEND AND AXIS FORMATTING
% -------------------------------------------------------------------------

hCaseA = ...
    patch( ...
        ax, ...
        nan, ...
        nan, ...
        colorCaseA, ...
        'EdgeColor', ...
        barEdgeColor);

hCaseB = ...
    patch( ...
        ax, ...
