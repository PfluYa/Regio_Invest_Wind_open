legend( ...
    ax, ...
    [hCaseA, hCaseB, hCaseC], ...
    { ...
        'Case A: nested logit', ...
        'Case B: available land', ...
        'Case C: NPV merit order' ...
    }, ...
    'Location', ...
    'southeast', ...
    'FontSize', ...
    9);

axis(ax, 'equal');
axis(ax, 'off');

xlim( ...
    ax, ...
    [ ...
        min(dataA.lonPoint) - 0.4, ...
        max(dataA.lonPoint) + 0.5 ...
    ]);

ylim( ...
    ax, ...
    [ ...
        min(dataA.latPoint) - 0.5, ...
        max(dataA.latPoint) + 2.2 ...
    ]);


%% ------------------------------------------------------------------------
% 8. EXPORT
% -------------------------------------------------------------------------

outputFigure = ...
    fullfile( ...
        resultsFolder, ...
        'Figure_4_allocation_comparison.pdf');

exportgraphics( ...
    fig, ...
    outputFigure, ...
    'ContentType', ...
    'vector');

fprintf( ...
    'Figure 4 saved to:\n%s\n', ...
    outputFigure);


%% ========================================================================
% LOCAL FUNCTIONS
% ========================================================================

function aligned = alignToReference(data, reference)

    [isMatched, idx] = ...
        ismember( ...
            reference.nutsID, ...
            data.nutsID);

    if any(~isMatched)

        error( ...
            'Mismatch in NUTS3 IDs across allocation cases.');
    end

    aligned = ...
        data(idx, :);
end


function capacityGW = aggregateCapacityByState(data, stateCodes)

    nutsID = ...
        string(data.nutsID);

    nuts1 = ...
        extractBetween( ...
            nutsID, ...
            1, ...
            3);

    capacityGW = ...
        zeros(numel(stateCodes), 1);

    for iState = 1:numel(stateCodes)

        idxState = ...
            nuts1 == stateCodes(iState);

        capacityGW(iState) = ...
            sum( ...
                data.capacityTotal(idxState), ...
                'omitnan') ./ ...
            1e6;
    end
end


function stateShape = combineRegionalPolygons(lonCells, latCells)

    stateShape = ...
        polyshape();

    for iRegion = 1:numel(lonCells)

        regionalShape = ...
            polyshape( ...
                lonCells{iRegion}, ...
                latCells{iRegion}, ...
                'Simplify', ...
                false);

        if isempty(stateShape.Vertices)

            stateShape = ...
                regionalShape;

        else

            stateShape = ...
                union( ...
                    stateShape, ...
                    regionalShape);
        end
    end
end
