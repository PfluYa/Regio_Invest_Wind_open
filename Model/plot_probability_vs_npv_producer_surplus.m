%% FIGURE 9: PRODUCER-SURPLUS COMPARISON AT THE CURRENT POLICY
% Reproduces the paper figure comparing the probability-based producer
% surplus with the NPV-based producer-surplus benchmark at s = 1.
%
% The required diagnostics are generated and saved by
% estimateInvestmentDecision.m in:
%   Results Paper/Results_scaling_capacity_based.mat
%
% Output:
%   Results Paper/Figure_9_producer_surplus_comparison.pdf

%% ------------------------------------------------------------------------
% 1. PATHS
% -------------------------------------------------------------------------

scriptPath = mfilename('fullpath');
scriptFolder = fileparts(scriptPath);
repoFolder = fileparts(scriptFolder);
resultsFolder = fullfile(repoFolder, 'Results Paper');

inputFile = fullfile( ...
    resultsFolder, ...
    'Results_scaling_capacity_based.mat');

outputFigure = fullfile( ...
    resultsFolder, ...
    'Figure_9_producer_surplus_comparison.pdf');

if ~isfile(inputFile)
    error('Results file not found: %s', inputFile);
end

%% ------------------------------------------------------------------------
% 2. LOAD s = 1 DIAGNOSTICS
% -------------------------------------------------------------------------

data = load(inputFile, 'baselineDiagnostics');

if ~isfield(data, 'baselineDiagnostics')
    error('The results file does not contain baselineDiagnostics.');
end

D = data.baselineDiagnostics;

requiredFields = { ...
    'effectiveRemunerationGrid', ...
    'normalizedSupply', ...
    'finalEffectiveRemuneration', ...
    'normalizedNpvSurplusHeight', ...
    'producerSurplusNpvBased', ...
    'producerSurplusProbabilityBased'};

for iField = 1:numel(requiredFields)
    if ~isfield(D, requiredFields{iField})
        error( ...
            'baselineDiagnostics is missing field "%s".', ...
            requiredFields{iField});
    end
end

%% ------------------------------------------------------------------------
% 3. PREPARE SERIES
% -------------------------------------------------------------------------

xGrid = ...
    D.effectiveRemunerationGrid .* 100;

qGrid = ...
    D.normalizedSupply;

xMax = ...
    D.finalEffectiveRemuneration .* 100;

npvHeight = ...
    D.normalizedNpvSurplusHeight;

psNpv_bnEUR = ...
    D.producerSurplusNpvBased ./ 1e9;

psProbability_bnEUR = ...
    D.producerSurplusProbabilityBased ./ 1e9;

%% ------------------------------------------------------------------------
% 4. CREATE FIGURE
% -------------------------------------------------------------------------

figure( ...
    'Position', [180 180 950 650], ...
    'Color', 'w');

% Area-equivalent representation of the NPV-based benchmark.
hNpv = patch( ...
    [0, xMax, xMax, 0], ...
    [0, 0, npvHeight, npvHeight], ...
    [0.70 0.70 0.70], ...
    'FaceAlpha', 0.20, ...
    'EdgeColor', [0.35 0.35 0.35], ...
    'LineStyle', '--', ...
    'LineWidth', 1.5);

hold on;

% Probability-based producer-surplus area.
hProbabilityArea = area( ...
    xGrid, ...
    qGrid, ...
    'FaceColor', [0.30 0.65 0.85], ...
    'FaceAlpha', 0.35, ...
    'EdgeColor', 'none');

% Model-implied synthetic supply response.
hSupply = plot( ...
    xGrid, ...
    qGrid, ...
    'Color', [0.85 0.30 0.05], ...
    'LineWidth', 2.5);

%% ------------------------------------------------------------------------
% 5. FORMATTING
% -------------------------------------------------------------------------

grid on;
box on;

xlabel('Effective remuneration (ct/kWh)');
ylabel('Normalized synthetic generation, Q / Q^*');
title('Producer-surplus comparison at s = 1');

xlim([0, xMax]);
ylim([0, 1.05]);

set(gca, ...
    'FontSize', 11, ...
    'LineWidth', 0.8);

legend( ...
    [hNpv, hProbabilityArea, hSupply], ...
    { ...
        sprintf( ...
            'Area-equivalent NPV-based PS (%.1f bn EUR/year)', ...
            psNpv_bnEUR), ...
        sprintf( ...
            'Probability-based producer surplus (%.1f bn EUR/year)', ...
            psProbability_bnEUR), ...
        'Normalized synthetic supply response' ...
    }, ...
    'Location', 'northwest');

%% ------------------------------------------------------------------------
% 6. EXPORT
% -------------------------------------------------------------------------

exportgraphics( ...
    gcf, ...
    outputFigure, ...
    'ContentType', 'vector');

fprintf('Figure 9 saved to:\n%s\n', outputFigure);
