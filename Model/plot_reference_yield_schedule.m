%% FIGURE 5: REFERENCE-YIELD CORRECTION SCHEDULES
% Shows the remuneration correction factor for alternative strengths of
% spatial differentiation:
%
%   corr(s) = 1 + s * (corr(1) - 1)
%
% with s = 0 denoting uniform remuneration and s = 1 the current
% reference-yield mechanism.
%
% Output:
%   Results Paper/Figure_5_reference_yield_correction_factors.pdf

scriptPath = ...
    mfilename('fullpath');

scriptFolder = ...
    fileparts(scriptPath);

repoFolder = ...
    fileparts(scriptFolder);

resultsFolder = ...
    fullfile(repoFolder, 'Results Paper');

if ~isfolder(resultsFolder)
    mkdir(resultsFolder);
end


%% ------------------------------------------------------------------------
% 1. CURRENT REFERENCE-YIELD SCHEDULE
% -------------------------------------------------------------------------

[relativeYieldNodes, currentCorrectionNodes] = ...
    getReferenceYieldSchedule();

% A fine grid is used only for visual interpolation. The same piecewise
% linear schedule as in the investment model is retained.
relativeYieldGrid = ...
    linspace( ...
        min(relativeYieldNodes), ...
        max(relativeYieldNodes), ...
        501);

currentCorrectionGrid = ...
    interp1( ...
        relativeYieldNodes, ...
        currentCorrectionNodes, ...
        relativeYieldGrid, ...
        'linear');


%% ------------------------------------------------------------------------
% 2. COUNTERFACTUAL SCALING FACTORS
% -------------------------------------------------------------------------

scaleFactors = ...
    [0, 0.5, 1.0, 1.5];

nScale = ...
    numel(scaleFactors);

correctionSchedules = ...
    zeros( ...
        numel(relativeYieldGrid), ...
        nScale);

for iScale = 1:nScale

    s = ...
        scaleFactors(iScale);

    correctionSchedules(:, iScale) = ...
        1 + ...
        s .* ...
        (currentCorrectionGrid - 1);
end


%% ------------------------------------------------------------------------
% 3. PLOT
% -------------------------------------------------------------------------

fig = ...
    figure( ...
        'Position', [200 180 820 540], ...
        'Color', 'w');

ax = ...
    axes(fig);

hold(ax, 'on');

lineHandles = ...
    gobjects(nScale, 1);

lineStyles = ...
    {'--', '-.', '-', ':'};

for iScale = 1:nScale

    lineHandles(iScale) = ...
        plot( ...
            ax, ...
            relativeYieldGrid, ...
            correctionSchedules(:, iScale), ...
            'LineStyle', ...
            lineStyles{iScale}, ...
            'LineWidth', ...
            2.0);
end

% Mark the statutory/current schedule nodes for s = 1.
idxCurrent = ...
    find(scaleFactors == 1, 1, 'first');

plot( ...
    ax, ...
    relativeYieldNodes, ...
    currentCorrectionNodes, ...
    'o', ...
    'MarkerSize', 4.5, ...
    'MarkerFaceColor', ...
    get(lineHandles(idxCurrent), 'Color'), ...
    'MarkerEdgeColor', ...
    get(lineHandles(idxCurrent), 'Color'), ...
    'HandleVisibility', ...
    'off');


%% ------------------------------------------------------------------------
% 4. FORMATTING
% -------------------------------------------------------------------------

xlabel( ...
    ax, ...
    'Yield relative to reference yield');

ylabel( ...
    ax, ...
    'Revenue correction factor');

xlim( ...
    ax, ...
    [0.5 1.5]);

ylim( ...
    ax, ...
    [0.6 2.0]);

xticks( ...
    ax, ...
    [0.5 0.75 1.0 1.25 1.5]);

yticks( ...
    ax, ...
    0.6:0.2:2.0);

grid(ax, 'on');
box(ax, 'on');

set( ...
    ax, ...
    'FontSize', 11, ...
    'LineWidth', 0.8);

legendLabels = { ...
    's = 0', ...
    's = 0.5', ...
    's = 1.0', ...
    's = 1.5'};

legend( ...
    ax, ...
    lineHandles, ...
    legendLabels, ...
    'Location', ...
    'northoutside', ...
    'Orientation', ...
    'horizontal', ...
    'Box', ...
    'off');


%% ------------------------------------------------------------------------
% 5. EXPORT
% -------------------------------------------------------------------------

outputFigure = ...
    fullfile( ...
        resultsFolder, ...
        'Figure_5_reference_yield_correction_factors.pdf');

exportgraphics( ...
    fig, ...
    outputFigure, ...
    'ContentType', ...
    'vector');

fprintf( ...
    'Figure 5 saved to:\n%s\n', ...
    outputFigure);
